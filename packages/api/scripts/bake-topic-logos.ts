// Writes the topic logos from Simple Icons (CC0 1.0, https://simpleicons.org): bun run --cwd packages/api bake:logos
// Only the logos topic-logos.ts names are written, so neither Worker ships the whole set. The brands stay their owners'
// trademarks, as Simple Icons' DISCLAIMER.md says.
import * as simpleIcons from "simple-icons";
import { topicLogoSlugs } from "./topic-logos.ts";

interface SimpleIcon {
  readonly slug: string;
  readonly hex: string;
  readonly path: string;
}

const bySlug = new Map(
  Object.values(simpleIcons as unknown as Record<string, SimpleIcon>).map((icon) => [icon.slug, icon]),
);

// The 24 unit mark sits in a 38 unit square, so it fills about two thirds of a tile and keeps a margin on any plate.
const svgOf = (icon: SimpleIcon) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-7 -7 38 38"><path fill="#${icon.hex}" d="${icon.path}"/></svg>`;

const luminance = (hex: string) => {
  const [r, g, b] = [0, 2, 4].map((at) => {
    const channel = Number.parseInt(hex.slice(at, at + 2), 16) / 255;
    return channel <= 0.04045 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4;
  }) as [number, number, number];
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};

// Brand colors are drawn for white, so a logo sits on white in both themes. One too pale to read on white, such as
// JavaScript's yellow, sits on ink instead.
const plateOf = (hex: string) => (1.05 / (luminance(hex) + 0.05) < 1.6 ? "dark" : "light");

export const bakeTopicLogos = () => {
  const svgs: Record<string, string> = {};
  const topics: Record<string, { readonly key: string; readonly plate: "light" | "dark" }> = {};
  for (const [topic, slug] of Object.entries(topicLogoSlugs)) {
    const icon = bySlug.get(slug);
    if (icon === undefined) throw new Error(`simple-icons has no ${slug}, for ${topic}`);
    const svg = svgOf(icon);
    const key = `${slug}.${new Bun.CryptoHasher("sha256").update(svg).digest("hex").slice(0, 10)}.svg`;
    svgs[key] = svg;
    topics[topic] = { key, plate: plateOf(icon.hex) };
  }
  return { topics, svgs };
};

const header = (what: string) =>
  [
    `// Generated by packages/api/scripts/bake-topic-logos.ts from simple-icons, CC0 1.0. ${what}`,
    "// Edit scripts/topic-logos.ts and run `bun run --cwd packages/api bake:logos`.",
    "",
  ].join("\n");

if (import.meta.main) {
  const baked = bakeTopicLogos();
  const sorted = <T>(record: Record<string, T>) =>
    Object.fromEntries(Object.entries(record).sort(([a], [b]) => (a < b ? -1 : 1)));
  await Bun.write(
    new URL("../src/topic-logos.gen.ts", import.meta.url),
    `${header("Each topic's logo file and the plate behind it.")}\nexport const topicLogos: Readonly<Record<string, { readonly key: string; readonly plate: "light" | "dark" }>> = {\n${Object.entries(
      sorted(baked.topics),
    )
      .map(
        ([topic, { key, plate }]) =>
          `  ${JSON.stringify(topic)}: { key: ${JSON.stringify(key)}, plate: ${JSON.stringify(plate)} },`,
      )
      .join("\n")}\n};\n`,
  );
  await Bun.write(
    new URL("../src/logo-svgs.gen.ts", import.meta.url),
    `${header("Each logo file's SVG.")}\nexport const logoSvgs: Readonly<Record<string, string>> = {\n${Object.entries(
      sorted(baked.svgs),
    )
      .map(([key, svg]) => `  ${JSON.stringify(key)}: ${JSON.stringify(svg)},`)
      .join("\n")}\n};\n`,
  );
}
